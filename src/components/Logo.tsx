const RATIO = 320 / 540;

export function Logo({ width, height, tone = "light", className = "" }: LogoProps) {
  const w = width ?? (height ? height / RATIO : 110);
  const h = height ?? w * RATIO;
  const waveColor = tone === "dark" ? "#E1EBF7" : "#8FB0DA";
  const waveOpacity = tone === "dark" ? 0.55 : 0.75;
  const textColor = tone === "dark" ? "#FFFFFF" : "#0A1F42";

  return (
    <svg
      viewBox="0 0 540 320"
      width={w}
      height={h}
      className={className}
      role="img"
      aria-label="Mayinvest"
      style={{ display: "block" }}
    >
      <g
        transform="translate(0,320) scale(0.1,-0.1)"
        fill={waveColor}
        fillOpacity={waveOpacity}
        fillRule="evenodd"
      >
        <path d={WAVES} />
      </g>
      {/* Texte à l'échelle d'origine : il s'emboîte exactement dans les vagues */}
      <g transform="translate(0,320) scale(0.1,-0.1)" fill={textColor} fillRule="evenodd">
        <path d={WORDMARK} />
      </g>
    </svg>
  );
}

